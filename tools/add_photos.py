"""Add a hand-picked batch of photos to the site without rebuilding everything.

  python3 tools/add_photos.py spec.json

spec.json is a list of {"src": path, "d": "YYYY-MM-DDTHH:MM:SS", "rot": 0|90|180|270,
"crop": [x0, y0, x1, y1] (fractions, optional), "est": true (optional)}.
Each photo is turned upright, cropped, stripped of metadata, saved as images/s_<date>_<n>.webp
plus a thumbnail, and merged into js/media.js and js/blur.js (sorted by date).
Photos within 6 bits (dHash) of one already on the site are skipped.
Run tools/score_quality.py afterwards.
"""
import json, os, sys
SPEC = sys.argv[1] if len(sys.argv) > 1 else 'spec.json'
sys.argv = sys.argv[:1] + ['']          # build_media reads argv at import; no raw folder here
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_media as bm
from PIL import Image, ImageOps

ROOT = bm.ROOT


def load(name, var):
    s = open(f'{ROOT}/js/{name}').read()
    return json.loads(s[s.index('=') + 1:s.rindex(';')].strip())


def main(spec_path):
    spec = json.load(open(spec_path))
    media = load('media.js', 'MEDIA')
    blur = json.loads(open(f'{ROOT}/js/blur.js').read().split('window.BLUR = ', 1)[1].split(';\n', 1)[0])
    keys = {m['key'] for m in media}
    hashes = []
    for m in media:
        if m['k'] == 'img':
            hashes.append(bm.dhash(Image.open(f"{ROOT}/{m['t']}")))
    added = 0
    for s in spec:
        im = ImageOps.exif_transpose(Image.open(s['src'])).convert('RGB')
        if s.get('rot'):
            im = im.rotate(s['rot'], expand=True)
        if s.get('crop'):
            x0, y0, x1, y1 = s['crop']; W, H = im.size
            im = im.crop((round(x0 * W), round(y0 * H), round(x1 * W), round(y1 * H)))
        h = bm.dhash(im)
        if any(bin(h ^ o).count('1') <= 6 for o in hashes):
            print('dup ', s['src']); continue
        hashes.append(h)
        d = s['d']; base = 's_' + d.replace('-', '').replace(':', '').replace('T', '_')
        n = 1
        while f'{base}_{n}.jpg' in keys:
            n += 1
        name = f'{base}_{n}.jpg'; keys.add(name)
        w, hh = bm.save_img(im, f'{ROOT}/images/{name}', f'{ROOT}/images/t/{name}')
        it = {'f': f'images/{name}', 't': f'images/t/{name}', 'k': 'img', 'd': d, 'w': w, 'h': hh, 'key': name}
        if s.get('est'):
            it['est'] = 1
        bm.enrich(it, im)
        blur[name] = it.pop('b')
        media.append(it); added += 1
    media.sort(key=lambda x: (x['d'] or '9999', x['f']))
    with open(f'{ROOT}/js/media.js', 'w') as fh:
        fh.write('/* Generated by tools/build_media.py - do not edit by hand. */\n')
        fh.write('window.MEDIA = ' + json.dumps(media, separators=(',', ':')).replace('},{', '},\n{') + ';\n')
    with open(f'{ROOT}/js/blur.js', 'w') as fh:
        fh.write('/* Generated: 12px blur-up placeholders, loaded after first paint. */\n')
        fh.write('window.BLUR = ' + json.dumps(blur, separators=(',', ':')) + ';\n')
        fh.write("document.dispatchEvent(new Event('blur-ready'));\n")
    print(f'added {added}, {len(media)} items')


if __name__ == '__main__':
    main(SPEC)
